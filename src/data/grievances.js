export function getGrievanceStats() {
  const open = GRIEVANCES.filter(g => g.status === 'open').length
  const assigned = GRIEVANCES.filter(g => g.status === 'assigned').length
  const resolved = GRIEVANCES.filter(g => g.status === 'resolved').length
  const critical = GRIEVANCES.filter(g => g.priority === 'critical').length
  const avgResolutionMs = GRIEVANCES
    .filter(g => g.resolvedAt)
    .map(g => new Date(g.resolvedAt) - new Date(g.submittedAt))
  const avgResolutionHrs = avgResolutionMs.length
    ? (avgResolutionMs.reduce((a, b) => a + b, 0) / avgResolutionMs.length / 3600000).toFixed(1)
    : '—'
  return { open, assigned, resolved, critical, total: GRIEVANCES.length, avgResolutionHrs }
}
